print("\n")# an empty line will be printed
print("Praba\nKaran")# \n will print the remaining characters in next line
print("praba\tkaran")# \t will create a tab space
print('This is praba\'s phone') # \ is used to consider the next character as special character to print
print(" He said, \"this is my phone\"") # He said, "this is my phone"
print('He said, "this is my phone"') # He said, "this is my phone" (without using \ )
print("This is backslash : \\") # to print \ --> added \\ to overcome backlash
